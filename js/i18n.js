  /* ------------------------------------------------------------------ */
  /* Engine                                                               */
  /* ------------------------------------------------------------------ */
  function getStored() {
    try { return localStorage.getItem(LANG_KEY); } catch (e) { return null; }
  }
  function getFs() {
    try { var n = parseInt(localStorage.getItem(FS_KEY), 10); return (n >= 0 && n < FS_STEPS.length) ? n : FS_DEFAULT; } catch (e) { return FS_DEFAULT; }
  }
  function setStoredLang(l) {
    try { localStorage.setItem(LANG_KEY, l); } catch (e) {}
  }
  function setStoredFs(i) {
    try { localStorage.setItem(FS_KEY, String(i)); } catch (e) {}
  }

  var current = SUPPORTED.indexOf(getStored()) !== -1 ? getStored() : DEFAULT_LANG;

  function t(key, vars) {
    var dict = DICT[current] || DICT.en;
    var v = dict[key];
    if (v === undefined) v = DICT.en[key]; /* fall back to English */
    if (v === undefined) v = key;
    if (vars) {
      for (var k in vars) {
        if (Object.prototype.hasOwnProperty.call(vars, k)) {
          v = v.split('{' + k + '}').join(vars[k]);
        }
      }
    }
    return v;
  }

  function applyText() {
    if (current === 'en') return; /* English is already in the markup */
    var nodes = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < nodes.length; i++) {
      var key = nodes[i].getAttribute('data-i18n');
      var val = DICT[current] && DICT[current][key];
      if (val === undefined) continue;
      val = val.split('{y}').join(String(new Date().getFullYear()));
      nodes[i].textContent = val;
    }
  }

  function applyHtml() {
    if (current === 'en') return;
    var nodes = document.querySelectorAll('[data-i18n-html]');
    for (var i = 0; i < nodes.length; i++) {
      var key = nodes[i].getAttribute('data-i18n-html');
      var val = DICT[current] && DICT[current][key];
      if (val !== undefined) nodes[i].innerHTML = val;
    }
  }

  function applyAttrs() {
    var i, n, key, val;
    var list = ['data-i18n-title', 'data-i18n-placeholder', 'data-i18n-label'];
    for (var a = 0; a < list.length; a++) {
      var attr = list[a];
      var nodes = document.querySelectorAll('[' + attr + ']');
      for (i = 0; i < nodes.length; i++) {
        n = nodes[i];
        key = n.getAttribute(attr);
        val = DICT[current] && DICT[current][key];
        if (val === undefined) val = DICT.en[key];
        if (val === undefined) continue;
        var target = attr === 'data-i18n-title' ? 'title' : attr === 'data-i18n-placeholder' ? 'placeholder' : 'aria-label';
        n.setAttribute(target, val);
      }
    }
    /* data-i18n-html on attribute-free nodes is handled above; here also swap
       aria-labels declared via data-i18n-aria on elements with existing labels. */
  }

  function applyTitle() {
    if (current === 'en') return;
    var file = window.location.pathname.split('/').pop() || 'index.html';
    if (file === '') file = 'index.html';
    var cls = file.replace('.html', '').replace(/[^a-z0-9]/gi, '').toLowerCase();
    var map = { index: 'title_index', about: 'title_about', mission: 'title_mission', divisions: 'title_divisions', admission: 'title_admission', gallery: 'title_gallery', contact: 'title_contact', '404': 'title_404' };
    var key = map[cls];
    if (key) document.title = t(key);
  }

  function apply() {
    var html = document.documentElement;
    html.setAttribute('lang', current);
    html.setAttribute('dir', current === 'ar' ? 'rtl' : 'ltr');
    applyText();
    applyHtml();
    applyAttrs();
    applyTitle();
    syncToolbar();
  }

  /* ------------------------------------------------------------------ */
  /* Toolbar (language + text size)                                       */
  /* ------------------------------------------------------------------ */
  function syncToolbar() {
    var btns = document.querySelectorAll('.aes-lang-btn');
    for (var i = 0; i < btns.length; i++) {
      var on = btns[i].getAttribute('data-lang') === current;
      btns[i].classList.toggle('is-active', on);
      btns[i].setAttribute('aria-pressed', on ? 'true' : 'false');
    }
  }

  function setLanguage(lang) {
    if (SUPPORTED.indexOf(lang) === -1) return;
    current = lang;
    setStoredLang(lang);
    apply();
    try { document.dispatchEvent(new window.CustomEvent('aes:langchange')); } catch (e) {}
  }

  function setFs(i) {
    i = Math.max(0, Math.min(FS_STEPS.length - 1, i));
    setStoredFs(i);
    document.documentElement.setAttribute('data-aes-fs', String(FS_STEPS[i]));
  }

  function wireToolbar() {
    var langBtns = document.querySelectorAll('.aes-lang-btn');
    for (var i = 0; i < langBtns.length; i++) {
      (function (b) {
        b.addEventListener('click', function () {
          setLanguage(b.getAttribute('data-lang'));
          document.body.classList.add('lang-switching');
          window.setTimeout(function () { document.body.classList.remove('lang-switching'); }, 450);
        });
      })(langBtns[i]);
    }
    var down = document.getElementById('fsDown');
    var up = document.getElementById('fsUp');
    var idx = getFs();
    setFs(idx);
    if (down) down.addEventListener('click', function () { setFs(getFs() + (-1)); apply(); });
    if (up) up.addEventListener('click', function () { setFs(getFs() + 1); apply(); });
    if (document.body) document.body.classList.add('i18n-ready');
  }

  /* ------------------------------------------------------------------ */
  /* Bootstrap                                                            */
  /* ------------------------------------------------------------------ */
  window.AES_I18N = {
    current: current,
    lang: function () { return current; },
    setLang: setLanguage,
    t: t,
    dict: DICT
  };

  apply();
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', wireToolbar);
  } else {
    wireToolbar();
  }
